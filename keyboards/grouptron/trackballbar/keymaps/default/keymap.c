bool encoder_hook_user(uint8_t index, bool clockwise)
{
	bool change = false;
	uint8_t dpi = user_config.dpi;

	if (index == 0) {
		if (chgdpi == true) {
			if (user_config.angle == 0 || user_config.angle == 1) {
				if (clockwise) {
					// down
					if (dpi < 30) {
						dpi++;
						change = true;
					}
				} else {
					// up
					if (dpi > 3) {
						dpi--;
						change = true;
					}
				}
			} else {
				if (clockwise) {
					// down
					if (dpi > 3) {
						dpi--;
						change = true;
					}
				} else {
					// up
					if (dpi < 30) {
						dpi++;
						change = true;
					}
				}
			}
			
			if (change == true) {
				tb_setdpi(dpi, true, true);
			}
			else {
				led_error();
			}
			return false;
		}
	}
	return true;
}

